"""Write an ovf ``CapTable`` as an OCF v1.2.0 package.

The writer emits what ovf knows and what OCF v1.2.0 requires. Where OCF requires a field
ovf has no value for (stakeholder type, votes per share, authorized shares, issue dates),
it writes a stated placeholder and a ``comments`` entry on the object that carries it, so
anyone reading the package can tell data from filler. Payout-relevant values are written
exactly or not at all.

Refused, each with an error naming the security and the gap:

* participating preferred with no cap. OCF v1.2.0 has no participating flag; an absent
  ``participation_cap_multiple`` reads as non-participating, and any cap would invent a
  term, so this structure cannot be expressed in the format;
* term debt and venture debt. OCF v1.2.0 has no object for non-convertible debt;
* convertible notes outside what the reader accepts: compound or PIK accrual (OCF has no
  compounding frequency), a day count other than Actual/365 Fixed, or a stated exit
  treatment (OCF has no repayment trigger and does not define ``exit_multiple``);
* SAFEs and every other instrument this adapter has no OCF mapping for;
* option pools with allocated options (ovf holds no grant, strike or vesting data);
* a number that needs more than the 10 decimal places OCF ``Numeric`` allows.

Seniority is written inverted, because OCF repays a higher number first: with ``k``
distinct ovf preferred seniorities, the most senior becomes OCF ``k + 1``, the most junior
``2``, and the common class ``1``. Note seniority is NOT inverted: OCF's convertible scale
has "1 being highest seniority", so the most senior ovf debt rank becomes OCF ``1``.

A note's maturity date and qualified-financing threshold have no OCF field. They are
written into comments and trigger text only, and must be supplied again as ``note_terms``
(``ovf.ocf.note_terms_from``) to read the package back.
"""

